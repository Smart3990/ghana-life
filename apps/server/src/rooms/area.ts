// T4: one live room per map area. Players in the room see each other and each other's walks.
//
// Design (master plan, zero-dollar rules):
// - Click-to-move: a player sends one "move_to" with the route when they tap. Other phones
//   animate the walk themselves, so the room handles a handful of messages, not a stream.
// - WebSocket hibernation: an idle room uses no compute.
// - Player state lives on each socket (serializeAttachment), so it survives hibernation
//   and needs no storage writes.
import { DurableObject } from 'cloudflare:workers';

const ROOM_CAP = 100; // players per room; measure and adjust (master plan, capacity plan)
const MIN_MS_BETWEEN_MOVES = 300; // ignore faster tapping
const MAX_MESSAGE_CHARS = 40_000;
const MAX_PATH_POINTS = 600;
const MAX_SPEED = 30; // metres per second

type LngLat = [number, number];

type Player = {
  id: string;
  name: string; // empty until the player says hello
  pos: LngLat | null; // where the current walk ends (or where they stand)
  path: LngLat[] | null; // the current walk
  startedAt: number; // server time the walk started, in ms
  speed: number;
  lastMove: number;
};

// What other players are allowed to see.
const publicView = (p: Player) => ({ id: p.id, name: p.name, pos: p.pos, path: p.path, startedAt: p.startedAt, speed: p.speed });

const isLngLat = (v: unknown): v is LngLat =>
  Array.isArray(v) && v.length === 2 && v.every((n) => typeof n === 'number' && Number.isFinite(n)) &&
  Math.abs(v[0]) <= 180 && Math.abs(v[1]) <= 90;

// Names are generated by the game for now; still, keep them short and plain.
const cleanName = (v: unknown) => (typeof v === 'string' ? v.replace(/[^\p{L}\p{N} '-]/gu, '').trim().slice(0, 24) : '');

function cleanPath(v: unknown): LngLat[] | null {
  if (!Array.isArray(v) || v.length < 2 || v.length > MAX_PATH_POINTS) return null;
  return v.every(isLngLat) ? (v as LngLat[]) : null;
}

export class AreaRoom extends DurableObject {
  async fetch(): Promise<Response> {
    if (this.ctx.getWebSockets().length >= ROOM_CAP) {
      return new Response('This area is full. Try again soon.', { status: 503 });
    }
    const pair = new WebSocketPair();
    const [client, server] = Object.values(pair);
    this.ctx.acceptWebSocket(server);
    const player: Player = { id: crypto.randomUUID().slice(0, 8), name: '', pos: null, path: null, startedAt: 0, speed: 0, lastMove: 0 };
    server.serializeAttachment(player);
    return new Response(null, { status: 101, webSocket: client });
  }

  async webSocketMessage(ws: WebSocket, raw: string | ArrayBuffer) {
    if (typeof raw !== 'string' || raw.length > MAX_MESSAGE_CHARS) return;
    let msg: { type?: string; name?: unknown; pos?: unknown; path?: unknown; speed?: unknown };
    try {
      msg = JSON.parse(raw);
    } catch {
      return;
    }
    const me = ws.deserializeAttachment() as Player;
    const now = Date.now();

    if (msg.type === 'hello') {
      me.name = cleanName(msg.name) || `Guest ${me.id.slice(0, 3)}`;
      me.pos = isLngLat(msg.pos) ? msg.pos : null;
      ws.serializeAttachment(me);
      const others = this.players().filter((p) => p.id !== me.id && p.name);
      ws.send(JSON.stringify({ type: 'snapshot', you: me.id, now, players: others.map(publicView) }));
      this.broadcast(ws, { type: 'joined', now, player: publicView(me) });
      return;
    }

    if (msg.type === 'move_to') {
      if (!me.name || now - me.lastMove < MIN_MS_BETWEEN_MOVES) return;
      const path = cleanPath(msg.path);
      const speed = typeof msg.speed === 'number' ? Math.min(Math.max(msg.speed, 1), MAX_SPEED) : 0;
      if (!path || !speed) return;
      Object.assign(me, { path, speed, startedAt: now, pos: path[path.length - 1], lastMove: now });
      ws.serializeAttachment(me);
      this.broadcast(ws, { type: 'walk', now, id: me.id, path, startedAt: now, speed });
      return;
    }

    if (msg.type === 'ping') ws.send(JSON.stringify({ type: 'pong', now }));
  }

  async webSocketClose(ws: WebSocket) {
    this.leave(ws);
  }

  async webSocketError(ws: WebSocket) {
    this.leave(ws);
  }

  private leave(ws: WebSocket) {
    const me = ws.deserializeAttachment() as Player | null;
    if (me) this.broadcast(ws, { type: 'left', id: me.id });
    try {
      ws.close(1000, 'bye');
    } catch {
      // already closed
    }
  }

  private players(): Player[] {
    return this.ctx.getWebSockets().map((s) => s.deserializeAttachment() as Player).filter(Boolean);
  }

  // Messages out to other players are free on Cloudflare; only incoming ones count.
  private broadcast(except: WebSocket, msg: object) {
    const text = JSON.stringify(msg);
    for (const s of this.ctx.getWebSockets()) {
      if (s === except) continue;
      try {
        s.send(text);
      } catch {
        // that player is gone; their close event will tidy up
      }
    }
  }
}
